/**
 * Kulak Yolculuğu — el yapımı ASCII bölüm haritaları (karo 32 px, 26 satır).
 *
 * Lejant:
 *  #  katı zemin / duvar          -  tek yönlü ince platform
 *  o  ses jetonu (♪)              G  altın koklea (gizli, +500)
 *  S  başlangıç                   C  kontrol noktası (bayrak)
 *  E  bölüm çıkışı                e  düşman (yürür; tema belirler)
 *  ^  tehlike (kıl/diken)         w  serumen (yapışkan, yavaşlatır)
 *  M  yatay hareketli platform    V  dikey hareketli platform
 *  D  damla düşüren kaynak        T  kulak zarı trambolini
 *  R  yörüngede dönen kemikçik    t  zamanlı (yanıp sönen) platform
 *  s  kıl hücresi yayı
 */

export const TILE = 32;

export type EnemyLook = { kind: 'emoji'; emoji: string } | { kind: 'bacteria' } | { kind: 'noise' };

export type Theme = {
  /** kamera arka planı */
  bg: number;
  /** paralaks katmanları için renkler */
  far: number; mid: number;
  /** katı karo renkleri */
  solid: number; solidTop: number; solidDark: number;
  /** tek yönlü platform rengi */
  plank: number;
  /** hareketli platform rengi */
  mover: number;
  /** tehlike rengi */
  hazard: number;
  /** paralaks deseni */
  pattern: 'auricle' | 'canal' | 'cavity' | 'cochlea';
  /** L4: karolar tonotopi rengine göre boyanır */
  tonotopy?: boolean;
  enemy: EnemyLook;
  enemySpeed: number;
  gravity: number;
  jumpVel: number;
  runSpeed: number;
};

export type LevelDef = {
  id: string;
  index: number;
  name: string;
  hint: string;
  /** süre bonusu için hedef saniye */
  par: number;
  map: string[];
  theme: Theme;
};

